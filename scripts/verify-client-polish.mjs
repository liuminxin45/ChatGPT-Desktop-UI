import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium } from 'playwright';
import { createDemoServer } from './serve-demo.mjs';
const output = new URL('../tests/output/client-polish/', import.meta.url);
await mkdir(output, { recursive: true });
const server = createDemoServer();
await new Promise(r => server.listen(0, '127.0.0.1', r));
const results = [], errors = [];
let browser;
try {
    const channel = process.env.UI_BROWSER_CHANNEL || 'msedge';
    browser = await chromium.launch({ headless: true, ...(channel === 'chromium' ? {} : { channel }) });
    for (const theme of ['light', 'dark'])
        for (const [width, height, scale] of [[1920, 1080, 1], [1280, 800, 1], [1536, 864, 1.25]]) {
            const context = await browser.newContext({ viewport: { width, height }, colorScheme: theme, deviceScaleFactor: scale });
            const page = await context.newPage();
            page.on('pageerror', e => errors.push(e.message));
            await page.goto(process.env.DEMO_URL || `http://127.0.0.1:${server.address().port}`);
            await page.getByRole('button', { name: 'Switch mode', exact: true }).waitFor();
            const rail = page.getByRole('navigation', { name: 'App navigation' });
            const home = rail.getByRole('button', { name: 'Home', exact: true });
            const plugins = rail.getByRole('button', { name: 'Plugins', exact: true });
            await page.mouse.move(width - 20, height - 20);
            await page.waitForTimeout(200);
            const selectedColor = await home.evaluate(el => getComputedStyle(el).backgroundColor);
            assert.equal(await plugins.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)');
            await plugins.hover();
            await page.waitForTimeout(200);
            const railHover = await plugins.evaluate(el => {
                const button = getComputedStyle(el), shell = getComputedStyle(el.closest('.kit-rail'));
                return { background: button.backgroundColor, shell: shell.backgroundColor, radius: button.borderRadius,
                    width: el.getBoundingClientRect().width, height: el.getBoundingClientRect().height };
            });
            const rgb = color => color.match(/[\d.]+/g).slice(0, 3).map(Number);
            assert.ok(Math.max(...rgb(railHover.background).map((value, index) => Math.abs(value - rgb(railHover.shell)[index]))) >= 10,
                'hovered rail tile visibly differs from the shell in both themes');
            assert.deepEqual([railHover.width, railHover.height, railHover.radius], [36, 36, '10px']);
            assert.equal(await home.evaluate(el => getComputedStyle(el).backgroundColor), selectedColor, 'hover leaves the selected tile intact');
            assert.equal(await home.getAttribute('aria-current'), 'page');
            await page.screenshot({ path: new URL(`rail-hover-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await page.mouse.move(width - 20, height - 20);
            await page.waitForTimeout(200);
            assert.equal(await plugins.evaluate(el => getComputedStyle(el).backgroundColor), 'rgba(0, 0, 0, 0)', 'hover fill clears on pointer exit');
            const componentsLink = page.locator('.client-window-actions').getByRole('link', { name: 'Components', exact: true });
            assert.equal(await componentsLink.getAttribute('href'), 'components/');
            await componentsLink.click();
            await page.getByRole('navigation', { name: 'Component families' }).waitFor();
            await page.getByRole('link', { name: 'Client', exact: true }).click();
            await page.getByRole('button', { name: 'Switch mode', exact: true }).waitFor();
            for (const selector of ['.client-project-row:first-child', '.client-chat-row--selected']) {
                if (selector.includes('selected'))
                    await page.getByRole('button', { name: 'Refine desktop navigation', exact: true }).first().click();
                const row = page.locator(selector).first();
                await row.hover();
                const trigger = row.locator('button[aria-haspopup=menu]').first();
                await trigger.click();
                await page.getByRole('menu').waitFor();
                await page.mouse.move(width - 40, 200);
                await page.waitForTimeout(200);
                const anchor = await trigger.boundingBox(), menu = await page.getByRole('menu').boundingBox();
                assert.ok(anchor && anchor.width > 0, 'open menu keeps its row anchor visible');
                assert.ok(menu.x > 52 && menu.y >= 8, 'row menu never falls back to window origin');
                assert.ok(Math.abs(menu.x - anchor.x) < menu.width + 10, 'menu stays next to the trigger');
                assert.ok(menu.x + menu.width <= width && menu.y + menu.height <= height, 'menu stays in viewport');
                await page.screenshot({ path: new URL(`${selector.includes('selected') ? 'chat' : 'project'}-menu-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
                await page.keyboard.press('Escape');
                await page.waitForTimeout(250);
                assert.equal(await trigger.evaluate(el => document.activeElement === el), true);
            }
            const input = page.getByRole('textbox', { name: 'Message', exact: true });
            await input.fill('Work with Codex\ngyq typography');
            const toolbarMenu = page.locator('.client-chat-toolbar [data-desktop-action="client.chat.actions.open"]');
            await toolbarMenu.click();
            await page.getByRole('menu').waitFor();
            await page.waitForTimeout(200);
            const toolbarAnchor = await toolbarMenu.boundingBox(), toolbarMenuBox = await page.getByRole('menu').boundingBox();
            assert.ok(toolbarMenuBox.x > 52 && toolbarMenuBox.y >= toolbarAnchor.y + toolbarAnchor.height && toolbarMenuBox.x + toolbarMenuBox.width <= width);
            assert.equal(await page.getByRole('menuitem', { name: 'Move to right pane', exact: true }).count(), 0);
            await page.screenshot({ path: new URL(`chat-toolbar-menu-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await page.keyboard.press('Escape');
            const contextTrigger = page.getByRole('button', { name: 'Chat context', exact: true });
            await contextTrigger.click();
            const contextPanel = page.locator('.client-context-panel');
            await contextPanel.waitFor();
            await page.waitForTimeout(200);
            const anchorBox = await contextTrigger.boundingBox(), contextBox = await contextPanel.boundingBox();
            assert.ok(contextBox.x > 52 && contextBox.y >= anchorBox.y + anchorBox.height && contextBox.x + contextBox.width <= width, JSON.stringify({ anchorBox, contextBox }));
            assert.equal(await contextPanel.locator('.client-context-sources button').count(), 3);
            await page.screenshot({ path: new URL(`chat-context-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await page.keyboard.press('Escape');
            await page.waitForTimeout(200);
            assert.equal(await contextTrigger.evaluate(el => document.activeElement === el), true);
            await page.getByRole('button', { name: 'Show tabs', exact: true }).click();
            const browserPane = page.getByRole('complementary', { name: 'Browser pane', exact: true });
            await browserPane.waitFor();
            const address = page.getByRole('textbox', { name: 'Search or enter a URL', exact: true });
            await address.fill('draft.example');
            await page.getByRole('button', { name: 'Expand pane', exact: true }).click();
            assert.equal(await input.isVisible(), false);
            await page.screenshot({ path: new URL(`browser-full-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await page.getByRole('button', { name: 'Restore pane', exact: true }).click();
            assert.equal(await input.inputValue(), 'Work with Codex\ngyq typography');
            await page.getByRole('button', { name: 'Expand chat', exact: true }).click();
            assert.equal(await browserPane.isVisible(), false);
            await page.getByRole('button', { name: 'Restore chat', exact: true }).click();
            assert.equal(await address.inputValue(), 'draft.example');
            await page.getByRole('button', { name: 'Hide browser pane', exact: true }).click();
            await input.press('Control+Home');
            const geometry = await input.evaluate(el => { const s = getComputedStyle(el); return { radius: s.borderRadius, scrollLeft: el.scrollLeft, scrollTop: el.scrollTop, paddingLeft: parseFloat(s.paddingLeft), height: el.clientHeight, scrollHeight: el.scrollHeight }; });
            assert.equal(geometry.radius, '0px');
            assert.equal(geometry.scrollLeft, 0);
            assert.equal(geometry.scrollTop, 0);
            assert.ok(geometry.paddingLeft >= 2);
            const sidebar = page.locator('.client-sidebar');
            const projectsSection = sidebar.locator('.client-sidebar-section').filter({ has: page.getByRole('heading', { name: 'Projects', exact: true }) });
            const recentsSection = sidebar.locator('.client-sidebar-section').filter({ has: page.getByRole('heading', { name: 'Recents', exact: true }) });
            const projectToggle = projectsSection.getByRole('button', { name: 'desktop-workspace', exact: true });
            const projectsToggle = projectsSection.getByRole('button', { name: 'Projects', exact: true });
            const recentsToggle = recentsSection.getByRole('button', { name: 'Recents', exact: true });
            const projectBody = page.locator('#client-project-chats-desktop');
            const toolbarBefore = await page.locator('.client-chat-toolbar').innerText();
            await projectToggle.click();
            assert.equal(await projectToggle.getAttribute('aria-expanded'), 'false');
            assert.equal(await projectBody.isVisible(), false);
            assert.equal(await projectBody.count(), 1, 'folded project children remain mounted');
            await page.waitForTimeout(200);
            await page.screenshot({ path: new URL(`project-folded-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await projectsToggle.click();
            await recentsToggle.click();
            assert.equal(await projectsToggle.getAttribute('aria-expanded'), 'false');
            assert.equal(await recentsToggle.getAttribute('aria-expanded'), 'false');
            assert.equal(await projectsSection.locator('.client-project-row').first().isVisible(), false);
            assert.equal(await recentsSection.locator('.client-chat-row').first().isVisible(), false);
            assert.equal(await input.inputValue(), 'Work with Codex\ngyq typography');
            assert.equal(await page.locator('.client-chat-toolbar').innerText(), toolbarBefore, 'folding never navigates away from the current chat');
            await projectsSection.getByRole('button', { name: 'Add new project', exact: true }).click();
            await page.getByRole('dialog', { name: 'Create project', exact: true }).waitFor();
            await page.keyboard.press('Escape');
            assert.equal(await projectsToggle.getAttribute('aria-expanded'), 'false', 'header actions do not toggle the section');
            await page.screenshot({ path: new URL(`sidebar-folded-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            await page.getByRole('button', { name: 'View activity', exact: true }).click();
            await page.getByRole('button', { name: 'View activity', exact: true }).click();
            assert.equal(await projectsToggle.getAttribute('aria-expanded'), 'false', 'section state survives activity view changes');
            await projectsToggle.press('Space');
            assert.equal(await projectToggle.getAttribute('aria-expanded'), 'false', 'nested fold state survives its parent folding');
            assert.equal(await projectsSection.getByRole('button', { name: 'design-studio', exact: true }).isVisible(), true);
            assert.equal(await recentsToggle.getAttribute('aria-expanded'), 'false');
            await projectToggle.press('Enter');
            assert.equal(await projectBody.isVisible(), true);
            await recentsToggle.press('Enter');
            assert.equal(await recentsSection.locator('.client-chat-row').first().isVisible(), true);
            assert.equal(await input.inputValue(), 'Work with Codex\ngyq typography');
            assert.equal(await page.locator('.client-chat-toolbar').innerText(), toolbarBefore);
            await page.emulateMedia({ reducedMotion: 'reduce' });
            assert.ok(await projectsToggle.locator('svg').evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) <= 0.00001));
            assert.ok(await projectToggle.locator('svg').last().evaluate(el => parseFloat(getComputedStyle(el).transitionDuration) <= 0.00001));
            await page.emulateMedia({ reducedMotion: 'no-preference' });
            const bar = await page.locator('.client-composer-context').boundingBox(), form = await page.locator('.client-composer--work').boundingBox();
            assert.ok(bar.y + bar.height - form.y >= 15, 'context background extends under the rounded composer');
            await page.getByRole('button', { name: 'Choose project', exact: true }).click();
            await page.getByRole('menuitem', { name: 'design-studio', exact: true }).click();
            assert.equal(await input.inputValue(), 'Work with Codex\ngyq typography');
            assert.match(await page.getByRole('button', { name: 'Choose project', exact: true }).innerText(), /design-studio/);
            await page.getByRole('button', { name: 'Choose computer', exact: true }).click();
            assert.equal(await page.getByRole('menuitem', { name: 'Set up remote', exact: true }).isEnabled(), false);
            await page.getByRole('menuitem', { name: 'This computer', exact: true }).click();
            assert.equal(await input.inputValue(), 'Work with Codex\ngyq typography');
            await input.focus();
            await page.screenshot({ path: new URL(`composer-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            const link = page.getByRole('button', { name: 'New chat', exact: true }).first();
            await link.hover();
            await page.mouse.down();
            assert.equal(await link.evaluate(el => getComputedStyle(el).transform), 'none');
            await page.mouse.up();
            await page.getByRole('button', { name: 'New tab', exact: true }).click();
            await page.getByRole('menuitem', { name: 'New tab in full view', exact: true }).click();
            assert.equal(await input.isVisible(), false);
            await page.getByRole('button', { name: 'Close tab', exact: true }).click();
            assert.equal(await input.isVisible(), true);
            await page.getByRole('button', { name: 'Switch mode', exact: true }).click();
            await page.getByRole('menuitem', { name: 'ChatGPT', exact: true }).click();
            await input.fill('Work with Codex\ngyq');
            await input.press('Control+Home');
            assert.equal(await input.evaluate(el => getComputedStyle(el).borderRadius), '0px');
            await page.screenshot({ path: new URL(`chat-input-${theme}-${width}.png`, output).pathname.replace(/^\/([A-Za-z]:)/, '$1') });
            results.push({ theme, width, height, scale, status: 'passed', geometry });
            await context.close();
        }
    assert.deepEqual(errors, []);
    await writeFile(new URL('report.json', output), JSON.stringify({ status: 'passed', results, errors }, null, 2));
    console.log(`PASS ${results.length} cases: sidebar buttons and disclosures, menu anchors, context selection, input clipping and draft retention.`);
}
finally {
    await browser?.close();
    await new Promise(r => server.close(r));
}
