import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
const manifest=JSON.parse(fs.readFileSync('package.json','utf8'));
assert.equal(manifest.name,'chatgpt-desktop-kit');assert.equal(manifest.version,'0.3.0');
const legacy=/(?:@ph[d]\/|--ph[d]-|data-ph[d]-|\bPh[d][A-Z]|\bph[d][:-]|\bph[d]T\b)/;
let checked=0;
const walk=directory=>{for(const entry of fs.readdirSync(directory,{withFileTypes:true})){const file=path.join(directory,entry.name);if(entry.isDirectory())walk(file);else if(/\.(css|tsx?|jsx?|mjs|json)$/.test(file)){assert.doesNotMatch(fs.readFileSync(file,'utf8'),legacy,file);checked++;}}};
walk('src');walk('dist');
const api=await import('../dist/index.js');for(const name of ['DesktopClientSurface','ClientSidebar','SidebarSection','DesktopMenu','SettingsGroup','SettingsField','Textarea'])assert.equal(typeof api[name]==='function'||typeof api[name]==='object',true,name);
assert.match(fs.readFileSync('dist/styles.css','utf8'),/--desktop-color-shell/);
console.log(JSON.stringify({status:'passed',neutralIdentity:manifest.name,checkedFiles:checked,referenceClient:JSON.parse(fs.readFileSync('docs/CLIENT_ALIGNMENT.json','utf8')).packageVersion}));
